								<h3>LOD 300 Ã¢â‚¬â€ Design Intent</h3>
								<p>LOD 300 is the standard for coordinated design and construction documentation. Structural elements are modelled with accurate dimensions, profiles, grades, and locations. Connections are represented with sufficient detail for coordination with architectural and MEP disciplines. At this level, the model can support reliable clash detection, quantity take-offs, and construction planning. Most structural coordination reviews operate at LOD 300 or LOD 350.</p>
								<p>LOD 350 extends LOD 300 by including interface elements Ã¢â‚¬â€ connection plates, embedments, hangers Ã¢â‚¬â€ that are needed for coordination with adjacent trades. It is the minimum level at which meaningful structural-to-MEP coordination can occur.</p>

								<h3>LOD 400 Ã¢â‚¬â€ Fabrication Ready</h3>
								<p>At LOD 400, the structural model contains sufficient detail for direct use in fabrication. Steel members are modelled with exact profiles, lengths, hole patterns, weld preparations, and finish specifications. Connection details are fully resolved at the component level. The model at LOD 400 can be used to generate shop drawings directly, produce accurate MTOs for procurement, and drive CNC fabrication equipment in modern steel workshops.</p>
								<p>VHS Engineering produces LOD 400 structural models using Tekla Structures, enabling direct integration between the design model and the fabrication process Ã¢â‚¬â€ reducing error, shortening delivery timelines, and improving quality traceability.</p>

								<h3>LOD 500 Ã¢â‚¬â€ As-Built</h3>
								<p>LOD 500 represents the as-built condition of the completed structure Ã¢â‚¬â€ the model as it was actually constructed, including any field modifications, substitutions, or dimensional deviations from the design intent. LOD 500 models are used for facilities management, maintenance planning, and future renovation or extension projects. They are typically produced by updating the construction model with as-built survey data at project completion.</p>

								<h3>Choosing the Right LOD for Your Project</h3>
								<p>Not every project needs a LOD 400 model, and not every element needs to be at the same LOD throughout the design process. A BIM Execution Plan (BEP) should specify the required LOD for each element category at each project phase, matched to the actual deliverables and uses of the model. Specifying LOD requirements that exceed what the project actually needs wastes modelling effort; specifying too low prevents the model from delivering its intended coordination or construction value.</p>

