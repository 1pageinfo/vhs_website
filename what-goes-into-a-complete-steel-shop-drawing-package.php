								<h3>3. Connection Details</h3>
								<p>Connection detail drawings show how members are joined Ã¢â‚¬â€ shear tab connections, end plate connections, moment connections, gusset plate bracing connections, and base plate details. They specify bolt grades, bolt diameters, weld sizes, throat thicknesses, and welding processes. Connection details must be consistent with the structural engineer's approved connection calculations.</p>
								<p>Incomplete connection details are the single most common cause of RFIs during steel fabrication. At VHS Engineering, every connection in the package is detailed to a standard that fabricators can work from without seeking further information.</p>

								<h3>4. Erection Drawings</h3>
								<p>Erection drawings show how the fabricated members are assembled on site Ã¢â‚¬â€ member orientations, splice locations, erection sequences, and temporary support requirements. They are used by the steel erector to plan crane picks, set out columns, and install beams and bracing in the correct order and orientation. Erection drawings must be coordinated with the member assembly drawings: every part mark on the erection drawing must correspond to a unique member in the shop drawing package.</p>

								<h3>5. Bill of Materials (BOM)</h3>
								<p>The BOM Ã¢â‚¬â€ sometimes called the Material Take-Off (MTO) Ã¢â‚¬â€ lists every steel member and plate in the project, with quantity, profile, grade, length, finish, and weight. It is used by the fabricator for material procurement, workshop scheduling, and delivery planning. An accurate BOM generated from the 3D model ensures that the fabricator orders the correct quantities and that procurement aligns with the fabrication and erection schedule.</p>

								<h3>6. Anchor Bolt Plans</h3>
								<p>Anchor bolt plans show the location, projection, diameter, grade, and setting details for the holding-down bolts that connect steel columns to concrete foundations. These drawings must be issued to the civil or concrete contractor before the foundations are cast Ã¢â‚¬â€ getting anchor bolt positions wrong is one of the most expensive errors in steel construction.</p>

